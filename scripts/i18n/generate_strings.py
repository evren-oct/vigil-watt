#!/usr/bin/env python3
"""Generate typed C# localization tables from translations.json.

Usage:
    python scripts/i18n/generate_strings.py

translations.json maps a stable key to {"zh": ..., "ru": ...}. Generated files are
checked in so the app builds without Python. Never edit generated files by hand.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "src" / "VigilWatt.App" / "Localization" / "translations.json"
OUT_DIR = ROOT / "src" / "VigilWatt.App" / "Localization"
HEADER = """// <auto-generated>
// Generated by scripts/i18n/generate_strings.py from translations.json.
// Do not edit manually.
// </auto-generated>
"""


def cs_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "\\r").replace("\n", "\\n") + '"'


def generate() -> None:
    data = json.loads(SOURCE.read_text(encoding="utf-8-sig"))
    keys = sorted(data)
    invalid = [k for k in keys if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", k)]
    if invalid:
        raise SystemExit(f"Invalid keys: {invalid[:10]}")
    # 缺字段时宁可报错，也别悄悄把中文写进 Ru 表——那会让整段界面“切了语言却没变”。
    missing = [k for k in keys if not data[k].get("zh") or not data[k].get("ru")]
    if missing:
        raise SystemExit(f"Missing zh/ru translations: {missing[:10]}")
    for culture, field in (("zh", "Zh"), ("ru", "Ru")):
        lines = [HEADER, "namespace VigilWatt.App.Localization;", "", "public sealed partial class Strings", "{"]
        lines.append(f"    private static readonly Dictionary<string, string> {field} = new()")
        lines.append("    {")
        for key in keys:
            lines.append(f"        [{cs_string(key)}] = {cs_string(data[key].get(culture, data[key]['zh']))},")
        lines.append("    };")
        lines.append("}")
        (OUT_DIR / f"Strings.{field}.cs").write_text("\n".join(lines) + "\n", encoding="utf-8")
    lines = [HEADER, "namespace VigilWatt.App.Localization;", "", "public sealed partial class Strings", "{"]
    for key in keys:
        lines.append(f"    public string {key} => Get({cs_string(key)});")
    lines.append("}")
    (OUT_DIR / "Strings.Properties.cs").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"generated {len(keys)} keys for zh-CN / ru-RU")


if __name__ == "__main__":
    generate()
